@dataclass(frozen=True)
class _Layout:
    """Per-aspect-ratio sizing knobs. Frozen dataclass so each ratio's
    tuning lives in one obvious place."""
    key: str
    width: int
    height: int
    padding: int
    title_size_max: int
    title_size_min: int
    sub1_size: int
    sub2_size: int
    eyebrow_size: int
    # Where the text panel sits as a fraction of canvas height.
    # E.g. 0.55 means the dark gradient panel starts 55% down from the
    # top. Tuned per aspect ratio so type breathes correctly.
    panel_top_frac: float


