# ────────────────────────── BACKGROUND PREP ──────────────────────────
def _prepare_bg(bg_bytes: bytes, layout: _Layout) -> Image.Image:
    """Crop / vertically-extend the AI watercolour to match this layout's
    aspect ratio without ever stretching the original (which would
    ruin painterly brush strokes). The strategy depends on whether the
    target is taller or wider than the source square:

      Square source → 1:1 target:    centre-crop, ~no-op
      Square source → 4:5 target:    crop the top portion (drop bottom)
      Square source → 9:16 target:   place square at top, fade into a
                                     darker tinted "fall-off" at the
                                     bottom so the dark text panel can
                                     extend coherently
      Square source → 16:9 target:   crop top + bottom equally to a
                                     landscape band

    The fall-off colour for the 9:16 case is sampled from the bottom
    edge of the source image so the seam is invisible.
    """
    src = Image.open(io.BytesIO(bg_bytes)).convert("RGB")
    # Slight warmth boost — the brand palette runs warm and a neutral
    # Gemini output reads a touch cool.
    src = ImageEnhance.Color(src).enhance(1.08)

    sw, sh = src.size
    tw, th = layout.width, layout.height
    src_ratio = sw / sh
    tgt_ratio = tw / th

    if abs(src_ratio - tgt_ratio) < 0.02:
        # Already close enough — straight resize.
        return src.resize((tw, th), Image.LANCZOS)

    if tgt_ratio > src_ratio:
        # Target is WIDER than source (e.g. 16:9). Scale to fit width,
        # then centre-crop top/bottom equally.
        scale_w = tw
        scale_h = int(sh * (tw / sw))
        scaled = src.resize((scale_w, scale_h), Image.LANCZOS)
        top = max(0, (scale_h - th) // 2)
        return scaled.crop((0, top, tw, top + th))

    # Target is TALLER than source (e.g. 9:16). Scale to fit width, then:
    #   - if the scaled image already covers the height, centre-crop
    #     vertically with a slight upward bias (so the visually
    #     interesting bit sits in the top 2/3 and the text panel
    #     extends into the lower 1/3).
    #   - otherwise: paste the scaled image at the top and extend
    #     downward with a tint sampled from its bottom edge so the
    #     seam is invisible behind the dark text panel.
    scale_w = tw
    scale_h = int(sh * (tw / sw))
    scaled = src.resize((scale_w, scale_h), Image.LANCZOS)
    if scale_h >= th:
        top = int(max(0, (scale_h - th) * 0.30))  # bias top
        return scaled.crop((0, top, tw, top + th))

    # Need to extend downward — sample bottom row mean colour, then fill.
    bottom_row = scaled.crop((0, scale_h - 8, scale_w, scale_h)).resize((1, 1)).getpixel((0, 0))
    canvas = Image.new("RGB", (tw, th), bottom_row)
    canvas.paste(scaled, (0, 0))
    # Soft vertical fade from scaled.bottom_row over the next ~120px so
    # the join feels painted, not bolted on.
    overlay_h = min(140, th - scale_h)
    if overlay_h > 0:
        fade = Image.new("RGBA", (tw, overlay_h), (0, 0, 0, 0))
        fdraw = ImageDraw.Draw(fade)
        for y in range(overlay_h):
            alpha = int(180 * (1 - y / overlay_h))
            fdraw.line([(0, y), (tw, y)], fill=bottom_row + (alpha,))
        canvas.paste(fade, (0, scale_h - overlay_h // 2), fade)
    # Light Gaussian on the seam region only so any horizontal banding
    # softens to mush — invisible under the text panel.
    canvas = canvas.filter(ImageFilter.GaussianBlur(0.4))
    return canvas


def _gradient_panel(width: int, height: int, top: int) -> Image.Image:
    """Smooth dark-forest gradient + solid floor for legibility. The
    ramp now uses a much steeper curve (t**0.5) so we reach ~70% alpha
    by panel mid-point, and the bottom 25% of the panel is essentially
    opaque (alpha 252). Tuned so all sub-text sits on solid colour."""
    panel = Image.new("RGBA", (width, height), (0, 0, 0, 0))
    pdraw = ImageDraw.Draw(panel)
    panel_h = height - top
    if panel_h <= 0:
        return panel
    # Two-stage ramp:
    #   0.00–0.60 of panel: fade from 0 → ~225 alpha (gradient zone)
    #   0.60–1.00 of panel: hold at ~252 (effectively opaque)
    knee = 0.60
    for y in range(top, height):
        t = (y - top) / panel_h
        if t < knee:
            alpha = int(230 * (t / knee) ** 0.55)
        else:
            alpha = 252
        pdraw.line([(0, y), (width, y)], fill=(14, 24, 14, alpha))
    return panel


def _wordmark_chip(draw: ImageDraw.ImageDraw, x: int, y: int, *, size: int) -> None:
    """Render the PATCH & POT wordmark in a dark pill — guaranteed
    legibility on busy backgrounds. Drawn directly onto the target
    image after the caller has alpha-composited the gradient panel."""
    font_size = int(size * 0.30)
    font = _font("sans-bold", font_size)
    text_w = draw.textlength("PATCH & POT", font=font)
    pad_x, pad_y = 22, 14
    w = int(text_w + pad_x * 2)
    h = int(font_size + pad_y * 2)
    # Draw the pill — semi-opaque forest with a fine sand stroke
    draw.rounded_rectangle([x, y, x + w, y + h], radius=8,
                            fill=(18, 28, 18, 215), outline=SAND, width=1)
    draw.text((x + pad_x, y + pad_y), "PATCH & POT", fill=SAND, font=font)
    # Terracotta accent rule under the pill
    draw.line([(x, y + h + 6), (x + int(w * 0.45), y + h + 6)],
              fill=TERRACOTTA, width=3)


# ────────────────────────── COMPOSITION ──────────────────────────
def _compose_watercolour(
    layout: _Layout, bg_bytes: bytes, *,
    eyebrow: str, title: str, sub1: str, sub2: str, cta: str,
) -> bytes:
    """Render one teaser at this layout with the AI watercolour as the
    background, dark gradient panel, and serif type composited on top."""
    bg = _prepare_bg(bg_bytes, layout).convert("RGBA")

    # Dark gradient panel for legibility
    panel_top = int(layout.height * layout.panel_top_frac)
    panel = _gradient_panel(layout.width, layout.height, panel_top)
    composed = Image.alpha_composite(bg, panel)

    # Subtle top-fade so the wordmark chip's pill doesn't sit on a
    # bright/busy painted patch (covers ~12% from the top).
    top_fade = Image.new("RGBA", (layout.width, layout.height), (0, 0, 0, 0))
    tdraw = ImageDraw.Draw(top_fade)
    fade_h = int(layout.height * 0.14)
    for y in range(fade_h):
        alpha = int(140 * (1 - y / fade_h))
        tdraw.line([(0, y), (layout.width, y)], fill=(18, 28, 18, alpha))
    composed = Image.alpha_composite(composed, top_fade)
    draw = ImageDraw.Draw(composed)

    # Top-left wordmark chip
    _wordmark_chip(draw, layout.padding, layout.padding, size=layout.padding)

    # Eyebrow inside the panel (uppercased "GROWING IN <region>")
    eyebrow_y = panel_top + int(layout.padding * 0.6)
    draw.text(
        (layout.padding, eyebrow_y),
        eyebrow.upper(),
        fill=(255, 232, 200),  # warm sand, +contrast vs pure SAND on dark
        font=_font("sans-regular", layout.eyebrow_size),
    )

    # Hero title — auto-fit + width-aware ellipsise
    text_col_width = layout.width - layout.padding * 2
    size = layout.title_size_max
    name_font = _font("serif-italic-bold", size)
    lines: list[str]
    while size >= layout.title_size_min:
        name_font = _font("serif-italic-bold", size)
        lines = _wrap_to_width(draw, title, name_font, text_col_width)
        widest = max(
            (draw.textlength(line, font=name_font) for line in lines),
            default=0,
        )
        if len(lines) <= 3 and widest <= text_col_width:
            break
        size -= 8
    else:
        name_font = _font("serif-italic-bold", layout.title_size_min)
        lines = _wrap_to_width(draw, title, name_font, text_col_width)[:3]
        for idx, line in enumerate(lines):
            if draw.textlength(line, font=name_font) <= text_col_width:
                continue
            trimmed = line
            while trimmed and draw.textlength(trimmed + "…", font=name_font) > text_col_width:
                trimmed = trimmed[:-1]
            lines[idx] = (trimmed.rstrip() + "…") if trimmed else "…"

    title_y = eyebrow_y + int(layout.eyebrow_size * 2.0)
    line_height = int(size * 1.05)
    for i, line in enumerate(lines):
        # Subtle shadow for ironclad contrast vs the painted backdrop
        draw.text((layout.padding + 2, title_y + i * line_height + 2),
                  line, fill=(0, 0, 0, 200), font=name_font)
        draw.text((layout.padding, title_y + i * line_height),
                  line, fill=(255, 250, 240), font=name_font)

    # Terracotta accent rule under the title block
    rule_y = title_y + len(lines) * line_height + 12
    draw.rectangle(
        [layout.padding, rule_y,
         layout.padding + max(80, int(layout.width * 0.10)), rule_y + 5],
        fill=TERRACOTTA,
    )

    # Sub-lines
    if sub1:
        draw.text(
            (layout.padding, rule_y + int(layout.sub1_size * 0.7)),
            sub1, fill=(255, 248, 230),
            font=_font("serif-italic", layout.sub1_size),
        )

    if sub2:
        sub2_y = rule_y + int(layout.sub1_size * 0.7) + int(layout.sub1_size * 1.5)
        draw.text(
            (layout.padding, sub2_y),
            sub2, fill=(255, 232, 200),
            font=_font("sans-regular", layout.sub2_size),
        )

    # Footer URL + CTA
    url_font = _font("sans-regular", max(22, layout.eyebrow_size - 2))
    url_y = layout.height - layout.padding - int(url_font.size * 1.1)
    draw.text((layout.padding, url_y), "patchandpot.app",
              fill=(255, 232, 200), font=url_font)

    cta_font = _font("sans-bold", max(22, layout.eyebrow_size - 2))
    cta_w = draw.textlength(cta, font=cta_font)
    draw.text(
        (layout.width - layout.padding - cta_w, url_y),
        cta, fill=TERRACOTTA, font=cta_font,
    )

    buf = io.BytesIO()
    composed.convert("RGB").save(buf, format="PNG", optimize=True)
    return buf.getvalue()


def _compose_letterpress(
    layout: _Layout, *,
    eyebrow: str, title: str, sub1: str, sub2: str, cta: str,
) -> bytes:
    """Fallback aesthetic — sand letterpress with a botanical sprig.
    Same composition as the original iter33 renderer; kept here so a
    missing/failed AI image never breaks the kit endpoint."""
    img = Image.new("RGB", (layout.width, layout.height), SAND)
    draw = ImageDraw.Draw(img)

    inset = max(28, layout.padding // 3)
    draw.rectangle(
        [inset, inset, layout.width - inset, layout.height - inset],
        fill=SURFACE, outline=None,
    )

    wordmark_font = _font("sans-bold", max(22, int(layout.padding * 0.28)))
    draw.text(
        (layout.padding, layout.padding),
        "PATCH & POT", fill=MOSS, font=wordmark_font, spacing=4,
    )
    draw.line(
        [(layout.padding, layout.padding + int(wordmark_font.size * 1.6)),
         (layout.padding + int(wordmark_font.size * 5.4), layout.padding + int(wordmark_font.size * 1.6))],
        fill=TERRACOTTA, width=2,
    )

    eyebrow_font = _font("sans-regular", layout.eyebrow_size)
    eyebrow_y = layout.padding + int(wordmark_font.size * 2.6)
    draw.text((layout.padding, eyebrow_y), eyebrow, fill=MOSS, font=eyebrow_font)

    text_col_width = layout.width - layout.padding * 2 - int(layout.width * 0.22)

    size = layout.title_size_max
    name_font = _font("serif-italic-bold", size)
    lines: list[str] = []
    while size >= layout.title_size_min:
        name_font = _font("serif-italic-bold", size)
        lines = _wrap_to_width(draw, title, name_font, text_col_width)
        widest = max(
            (draw.textlength(line, font=name_font) for line in lines),
            default=0,
        )
        if len(lines) <= 3 and widest <= text_col_width:
            break
        size -= 8
    else:
        name_font = _font("serif-italic-bold", layout.title_size_min)
        lines = _wrap_to_width(draw, title, name_font, text_col_width)[:3]
        for idx, line in enumerate(lines):
            if draw.textlength(line, font=name_font) <= text_col_width:
                continue
            trimmed = line
            while trimmed and draw.textlength(trimmed + "…", font=name_font) > text_col_width:
                trimmed = trimmed[:-1]
            lines[idx] = (trimmed.rstrip() + "…") if trimmed else "…"

    name_y = eyebrow_y + int(layout.eyebrow_size * 2.4)
    line_height = int(size * 1.08)
    for i, line in enumerate(lines):
        draw.text((layout.padding, name_y + i * line_height), line, fill=FOREST, font=name_font)

    rule_y = name_y + len(lines) * line_height + 14
    draw.rectangle(
        [layout.padding, rule_y, layout.padding + max(60, int(layout.width * 0.08)), rule_y + 4],
        fill=TERRACOTTA,
    )

    if sub1:
        draw.text((layout.padding, rule_y + int(layout.sub1_size * 0.9)),
                  sub1, fill=INK, font=_font("serif-italic", layout.sub1_size))

    if sub2:
        draw.text((layout.padding, rule_y + int(layout.sub1_size * 0.9) + int(layout.sub1_size * 1.4)),
                  sub2, fill=MOSS, font=_font("sans-regular", layout.sub2_size))

    url_font = _font("sans-regular", max(20, layout.eyebrow_size - 2))
    url_y = layout.height - layout.padding - int(url_font.size * 1.1)
    draw.text((layout.padding, url_y), "patchandpot.app", fill=MOSS, font=url_font)

    cta_font = _font("sans-bold", max(20, layout.eyebrow_size - 2))
    cta_w = draw.textlength(cta, font=cta_font)
    draw.text(
        (layout.width - layout.padding - cta_w, url_y),
        cta, fill=TERRACOTTA, font=cta_font,
    )

    # Decorative botanical sprig anchored right or bottom
    _draw_botanical(
        draw,
        cx=layout.width - layout.padding - int(layout.width * 0.09),
        cy=layout.height / 2,
        scale=1.8,
    )

    draw.rectangle(
        [inset, inset, layout.width - inset, layout.height - inset],
        outline=(45, 74, 34, 80), width=1,
    )

    buf = io.BytesIO()
    img.save(buf, format="PNG", optimize=True)
    return buf.getvalue()


# ────────────────────────── PUBLIC API ──────────────────────────
def render_kit_images(
    patch_name: str,
    region_name: str,
    plant_count: int,
    bg_image_bytes: Optional[bytes] = None,
) -> Dict[str, bytes]:
    """Render all four social-kit teasers.

    When `bg_image_bytes` is supplied (the cached AI watercolour for this
    snapshot) we use the watercolour aesthetic. When it's `None` we
    silently fall back to the letterpress version — caller decides
    whether to retry the LLM next request.
    """
    plant_label = "plant" if plant_count == 1 else "plants"
    eyebrow = "A SHARED GARDEN"
    sub1 = f"Growing in {region_name}" if region_name else "Growing somewhere lovely"
    sub2 = f"{plant_count} {plant_label} tracked  ·  monthly seasonal guide"
    cta = "OPEN  →"

    out: Dict[str, bytes] = {}
    for layout in _LAYOUTS:
        if bg_image_bytes:
            try:
                out[layout.key] = _compose_watercolour(
                    layout, bg_image_bytes,
                    eyebrow=eyebrow, title=patch_name,
                    sub1=sub1, sub2=sub2, cta=cta,
                )
                continue
            except Exception:  # noqa: BLE001 — never break the kit on one bad bg
                # Fall through to letterpress for THIS layout. We keep
                # going so we don't 500 the whole download on a single
                # malformed image.
                pass
        out[layout.key] = _compose_letterpress(
            layout,
            eyebrow=eyebrow, title=patch_name, sub1=sub1, sub2=sub2, cta=cta,
        )
    return out


def build_kit_zip(
    *,
    patch_name: str,
    region_name: str,
    plant_count: int,
    captions: Optional[Dict[str, str]] = None,
    bg_image_bytes: Optional[bytes] = None,
) -> bytes:
    """Bundle the four teasers + a captions.txt (if captions are supplied)
    + a small README into a single ZIP archive ready for download."""
    images = render_kit_images(patch_name, region_name, plant_count, bg_image_bytes)

    buf = io.BytesIO()
    with zipfile.ZipFile(buf, "w", zipfile.ZIP_DEFLATED) as zf:
        for stem, png in images.items():
            zf.writestr(f"{stem}.png", png)

        if captions:
            lines = [
                "PATCH & POT — SOCIAL MEDIA CAPTIONS",
                "=" * 40,
                "",
                "Below is one ready-to-paste caption per image. Pick the matching",
                "platform when you upload. All captions are seeds — feel free to",
                "tweak emoji, hashtags or tone to match your account voice.",
                "",
            ]
            label_map = {
                "instagram_square":   "Instagram (square feed post — 1:1)",
                "instagram_portrait": "Instagram (portrait feed post — 4:5)",
                "reels_story":        "Reels / TikTok / Stories / YouTube Shorts (9:16)",
                "youtube_twitter":    "Twitter / YouTube cover (16:9)",
            }
            for stem, label in label_map.items():
                caption = captions.get(stem)
                if not caption:
                    continue
                lines += [label, "-" * len(label), caption.strip(), "", ""]
            zf.writestr("captions.txt", "\n".join(lines))

        readme = (
            "PATCH & POT — SOCIAL MEDIA KIT\n"
            "==============================\n\n"
            "Four ready-to-post images of your patch, sized for every "
            "major social platform, plus a captions.txt with seed copy.\n\n"
            "Files\n-----\n"
            "  instagram_square.png    1080×1080  Instagram feed (square)\n"
            "  instagram_portrait.png  1080×1350  Instagram feed (portrait)\n"
            "  reels_story.png         1080×1920  Reels / TikTok / Stories / Shorts\n"
            "  youtube_twitter.png     1920×1080  Twitter card / YouTube cover\n"
            "  captions.txt            One caption per image\n\n"
            "Tip: post the 9:16 to your Stories with a 'link sticker' pointing\n"
            "at your patch URL — that's the highest-conversion surface.\n\n"
            f"Patch: {patch_name}\n"
            f"Region: {region_name or '—'}\n"
            f"Plants tracked: {plant_count}\n"
        )
        zf.writestr("README.txt", readme)

    return buf.getvalue()
