"""Seasonal Growing Journal — A4 PDF builder using reportlab.

Pulls the structured guidance object that `/api/guidance` already returns
(region- and month- specific, AI-generated by Claude in the user's language)
and renders it as a clean, printable PDF.
"""

from io import BytesIO

import qrcode
from reportlab.lib import colors
from reportlab.lib.pagesizes import A4, landscape
from reportlab.lib.styles import ParagraphStyle, getSampleStyleSheet
from reportlab.lib.units import mm
from reportlab.platypus import (
    BaseDocTemplate, Frame, Image as RLImage, KeepTogether, PageBreak,
    PageTemplate, Paragraph, Spacer, Table, TableStyle,
)

FOREST = colors.HexColor("#21372A")
TERRACOTTA = colors.HexColor("#C2553A")
INK = colors.HexColor("#2B2A26")
MOSS = colors.HexColor("#5C6B57")
SAND = colors.HexColor("#F6F1E7")
BORDER = colors.HexColor("#D6D2C4")


def _styles():
    base = getSampleStyleSheet()
    return {
        "eyebrow": ParagraphStyle("eyebrow", parent=base["BodyText"],
            fontName="Helvetica", fontSize=8, textColor=MOSS, spaceAfter=4),
        "h1": ParagraphStyle("h1", parent=base["Title"],
            fontName="Times-Roman", fontSize=26, leading=30, textColor=FOREST, spaceAfter=12),
        "h2": ParagraphStyle("h2", parent=base["Heading2"],
            fontName="Times-Roman", fontSize=15, leading=19, textColor=FOREST,
            spaceBefore=14, spaceAfter=6),
        "h3": ParagraphStyle("h3", parent=base["Heading3"],
            fontName="Helvetica-Bold", fontSize=11, leading=14, textColor=TERRACOTTA,
            spaceBefore=8, spaceAfter=2),
        "body": ParagraphStyle("body", parent=base["BodyText"],
            fontName="Helvetica", fontSize=10, leading=14, textColor=INK, spaceAfter=6),
        "small": ParagraphStyle("small", parent=base["BodyText"],
            fontName="Helvetica", fontSize=8.5, leading=11.5, textColor=MOSS),
    }


def _doc(buf, *, pagesize=A4):
    """A single-frame document with header rule + footer."""
    doc = BaseDocTemplate(
        buf, pagesize=pagesize,
        leftMargin=18 * mm, rightMargin=18 * mm,
        topMargin=20 * mm, bottomMargin=18 * mm,
        title="Patch & Pot — Seasonal Growing Journal",
    )
    frame = Frame(doc.leftMargin, doc.bottomMargin, doc.width, doc.height, id="frame")

    def _on_page(canvas, _doc):
        canvas.saveState()
        canvas.setFont("Helvetica", 7.5)
        canvas.setFillColor(MOSS)
        canvas.drawCentredString(pagesize[0] / 2, 10 * mm, "Patch & Pot — patchandpot")
        canvas.setStrokeColor(BORDER)
        canvas.setLineWidth(0.4)
        canvas.line(doc.leftMargin, pagesize[1] - 13 * mm,
                    pagesize[0] - doc.rightMargin, pagesize[1] - 13 * mm)
        canvas.restoreState()

    doc.addPageTemplates([PageTemplate(id="default", frames=[frame], onPage=_on_page)])
    return doc


def _esc(text) -> str:
    """Escape the four chars reportlab's mini-XML treats as markup."""
    return (
        str(text or "")
        .replace("&", "&amp;")
        .replace("<", "&lt;")
        .replace(">", "&gt;")
    )


def _para(text, style):
    """Plain-text paragraph — escapes any markup characters."""
    if not text:
        return None
    return Paragraph(_esc(text), style)


def _rich(markup, style):
    """Paragraph that *renders* reportlab markup (<b>, <i>, <font>).
    Caller MUST `_esc()` any user-provided interpolations themselves.
    """
    if not markup:
        return None
    return Paragraph(markup, style)


def build_seasonal_pdf(*, guidance: dict, region_name: str, month_label: str,
                       language: str, orientation: str = "portrait",
                       qr_url: str | None = None) -> bytes:
    """Render a full seasonal journal PDF.

    `guidance` is the JSON dict returned by /api/guidance — keys: plant_now,
    harvest_now, tasks, pests (each a list of typed objects).
    `qr_url` (optional): URL encoded into a small QR on the My-notes page so
    the printed PDF stays a re-entry point to the live site.
    """
    pagesize = landscape(A4) if orientation == "landscape" else A4
    buf = BytesIO()
    doc = _doc(buf, pagesize=pagesize)
    s = _styles()

    story = [
        _para("SEASONAL GROWING JOURNAL", s["eyebrow"]),
        _para(f"{month_label} — {region_name}", s["h1"]),
        _para(
            f"Personalised for {region_name}. Use this as a working print-out — "
            "tick tasks as you do them, jot the variety you sowed in the margin, "
            "circle anything you want to try next year.",
            s["body"],
        ),
        Spacer(1, 4 * mm),
    ]

    # ── Plant now ─────────────────────────────────────────────────────────
    plant_now = guidance.get("plant_now") or []
    if plant_now:
        story.append(_para("Sow & plant this month", s["h2"]))
        for p in plant_now:
            block = []
            block.append(_rich(
                f"<b>{_esc((p.get('name') or '').strip())}</b>"
                + (f"  <font color='#5C6B57'>· {_esc(p.get('kind'))}</font>" if p.get("kind") else ""),
                s["h3"],
            ))
            if p.get("why"):
                block.append(_para(p["why"], s["body"]))
            if p.get("how"):
                block.append(_rich(f"<i>How:</i> {_esc(p['how'])}", s["small"]))
            story.append(KeepTogether([b for b in block if b]))

    # ── Harvest ───────────────────────────────────────────────────────────
    harvest = guidance.get("harvest_now") or []
    if harvest:
        story.append(_para("Harvest now", s["h2"]))
        for h in harvest:
            block = [_rich(f"<b>{_esc((h.get('name') or '').strip())}</b>", s["h3"])]
            if h.get("tip"):
                block.append(_para(h["tip"], s["body"]))
            story.append(KeepTogether(block))

    # ── Tasks ─────────────────────────────────────────────────────────────
    tasks = guidance.get("tasks") or []
    if tasks:
        story.append(PageBreak())
        story.append(_para("Tasks", s["h2"]))
        for t in tasks:
            block = [
                _rich(f"<b>☐ {_esc((t.get('title') or '').strip())}</b>", s["h3"]),
            ]
            if t.get("detail"):
                block.append(_para(t["detail"], s["body"]))
            story.append(KeepTogether(block))

    # ── Pest watch ────────────────────────────────────────────────────────
    pests = guidance.get("pests") or []
    if pests:
        story.append(_para("Pest watch", s["h2"]))
        for pest in pests:
            block = [_rich(f"<b>{_esc((pest.get('name') or '').strip())}</b>", s["h3"])]
            if pest.get("signs"):
                block.append(_rich(f"<i>Signs:</i> {_esc(pest['signs'])}", s["body"]))
            if pest.get("control"):
                block.append(_rich(f"<i>Control:</i> {_esc(pest['control'])}", s["body"]))
            story.append(KeepTogether(block))

    # ── My notes — blank grid the user pens in by hand ────────────────────
    story.append(PageBreak())
    story.append(_para(f"My notes — {month_label}, {region_name}", s["h2"]))
    story.append(_para(
        "Jot down what you actually planted, where, and how it grew. "
        "Future you (and next year's PDF) will thank you.",
        s["body"],
    ))
    story.append(Spacer(1, 3 * mm))

    # Column widths sized to the active page (portrait or landscape).
    content_w = pagesize[0] - 18 * mm * 2
    col_widths = [
        content_w * 0.14,  # Date
        content_w * 0.26,  # Sown / planted
        content_w * 0.22,  # Where
        content_w * 0.38,  # Notes
    ]
    header = ["Date", "Sown / planted", "Where", "Notes / how it went"]
    rows = [header] + [[""] * 4 for _ in range(18)]

    notes_tbl = Table(rows, colWidths=col_widths, rowHeights=[8 * mm] + [11 * mm] * 18)
    notes_tbl.setStyle(TableStyle([
        ("FONT", (0, 0), (-1, 0), "Helvetica-Bold", 9),
        ("TEXTCOLOR", (0, 0), (-1, 0), FOREST),
        ("BACKGROUND", (0, 0), (-1, 0), SAND),
        ("LINEBELOW", (0, 0), (-1, 0), 0.6, FOREST),
        ("GRID", (0, 1), (-1, -1), 0.3, BORDER),
        ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
        ("LEFTPADDING", (0, 0), (-1, -1), 4),
        ("RIGHTPADDING", (0, 0), (-1, -1), 4),
        ("TOPPADDING", (0, 0), (-1, 0), 4),
        ("BOTTOMPADDING", (0, 0), (-1, 0), 4),
    ]))
    story.append(notes_tbl)

    # QR back to the live site — turns the printed PDF into a re-entry point.
    if qr_url:
        qr_img = qrcode.make(qr_url)
        qr_buf = BytesIO()
        qr_img.save(qr_buf, format="PNG")
        qr_buf.seek(0)
        qr_flowable = RLImage(qr_buf, width=22 * mm, height=22 * mm)
        caption = _para(
            f"Scan to revisit this guide online — your access stays unlocked.   {qr_url}\n"
            "Generated by Patch & Pot. Climate, weather and microsites vary widely — "
            "treat this as a thoughtful starting point, not a strict rulebook.",
            s["small"],
        )
        qr_row = Table(
            [[qr_flowable, caption]],
            colWidths=[26 * mm, content_w - 26 * mm],
        )
        qr_row.setStyle(TableStyle([
            ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
            ("LEFTPADDING", (0, 0), (-1, -1), 0),
            ("RIGHTPADDING", (0, 0), (-1, -1), 0),
            ("TOPPADDING", (0, 0), (-1, -1), 0),
            ("BOTTOMPADDING", (0, 0), (-1, -1), 0),
        ]))
        story.append(Spacer(1, 4 * mm))
        story.append(qr_row)
    else:
        story.append(Spacer(1, 6 * mm))
        story.append(_para(
            "Generated by Patch & Pot. Climate, weather and microsites vary widely — "
            "treat this as a thoughtful starting point, not a strict rulebook.",
            s["small"],
        ))

    doc.build([item for item in story if item is not None])
    return buf.getvalue()
