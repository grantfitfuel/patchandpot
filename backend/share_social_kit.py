"""Social Media Kit — render four AI-watercolour-backed teasers and ship
them as a single ZIP alongside platform-tuned captions.

Aesthetic (iter37 redesign): each patch gets ONE unique watercolour
illustration generated by Gemini Nano Banana, then composited under
a dark gradient panel + serif type per aspect ratio. The single
square watercolour is cropped / vertically-extended per format so we
spend just one LLM call per snapshot — cached forever in MongoDB.

Aspect ratios (all 1080-wide minimum so they survive Instagram/TikTok
re-compression):

    instagram_square  1080×1080   1:1   feed posts
    instagram_portrait 1080×1350  4:5   feed posts (taller, more screen)
    reels_story        1080×1920  9:16  Reels / TikTok / Stories / YouTube Shorts
    youtube_twitter    1920×1080  16:9  YouTube cover / Twitter card

Fallback policy: if the caller passes `bg_image_bytes=None` (because the
LLM call failed or the budget is exhausted) we render the previous
letterpress aesthetic so the user still gets a usable kit. We never
500 the social-kit endpoint over an LLM hiccup.

CACHE INVALIDATION
------------------
`RENDER_VERSION` below is part of every cache key (in `shared_patch_social_kit`
+ `shared_patch_story_png` + `shared_patch_watercolour`). Bump it whenever
the *renderer* changes in a user-visible way — bumping forces every
existing cached ZIP/PNG to be regenerated on the next request, regardless
of whether the underlying snapshot was edited.

Past renderer versions:
  iter33-letterpress    — original sand-letterpress aesthetic
  iter37-watercolour-v1 — AI-painted backgrounds with dark gradient panel
"""
from __future__ import annotations

# Public — used by routers/share.py to namespace cache lookups so an
# aesthetic change always invalidates stale ZIPs even if the snapshot
# itself hasn't been edited.
