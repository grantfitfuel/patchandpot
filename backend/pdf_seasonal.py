"""Seasonal Growing Journal — A4 PDF builder using reportlab.

Pulls the structured guidance object that `/api/guidance` already returns
(region- and month- specific, AI-generated by Claude in the user's language)
and renders it as a clean, printable PDF.

`build_seasonal_pdf` is the only public entry point — composition of the
private `_section_*` / `_footer_*` helpers below. The helpers all share
the same signature `(story, ..., styles)` so a new section can be inserted
between two existing ones in a single line of `build_seasonal_pdf`.
"""

from io import BytesIO

import qrcode
from reportlab.lib import colors
from reportlab.lib.pagesizes import A4, landscape
from reportlab.lib.styles import ParagraphStyle, getSampleStyleSheet
from reportlab.lib.units import mm
from reportlab.platypus import (
    BaseDocTemplate, Frame, Image as RLImage, KeepTogether, PageBreak,
    PageTemplate, Paragraph, Spacer, Table, TableStyle,
)

from pdf_illustrations import monthly_drawing

FOREST = colors.HexColor("#21372A")
TERRACOTTA = colors.HexColor("#C2553A")
INK = colors.HexColor("#2B2A26")
MOSS = colors.HexColor("#5C6B57")
SAND = colors.HexColor("#F6F1E7")
BORDER = colors.HexColor("#D6D2C4")


def _styles():
    base = getSampleStyleSheet()
    return {
        "eyebrow": ParagraphStyle("eyebrow", parent=base["BodyText"],
            fontName="Helvetica", fontSize=8, textColor=MOSS, spaceAfter=4),
        "h1": ParagraphStyle("h1", parent=base["Title"],
            fontName="Times-Roman", fontSize=26, leading=30, textColor=FOREST, spaceAfter=12),
        "h2": ParagraphStyle("h2", parent=base["Heading2"],
            fontName="Times-Roman", fontSize=15, leading=19, textColor=FOREST,
            spaceBefore=14, spaceAfter=6),
        "h3": ParagraphStyle("h3", parent=base["Heading3"],
            fontName="Helvetica-Bold", fontSize=11, leading=14, textColor=TERRACOTTA,
            spaceBefore=8, spaceAfter=2),
        "body": ParagraphStyle("body", parent=base["BodyText"],
            fontName="Helvetica", fontSize=10, leading=14, textColor=INK, spaceAfter=6),
        "small": ParagraphStyle("small", parent=base["BodyText"],
            fontName="Helvetica", fontSize=8.5, leading=11.5, textColor=MOSS),
    }


def _doc(buf, *, pagesize=A4):
    doc = BaseDocTemplate(
        buf, pagesize=pagesize,
        leftMargin=18 * mm, rightMargin=18 * mm, topMargin=18 * mm, bottomMargin=18 * mm,
        title="Patch & Pot Seasonal Journal",
    )
    frame = Frame(
        doc.leftMargin, doc.bottomMargin,
        doc.width, doc.height, id="body",
    )

    def _on_page(canvas, _doc):
        canvas.saveState()
        canvas.setFillColor(MOSS)
        canvas.setFont("Helvetica", 8)
        canvas.drawString(doc.leftMargin, 13 * mm, "PATCH & POT  ·  SEASONAL JOURNAL")
        canvas.drawRightString(
            pagesize[0] - doc.rightMargin, 13 * mm, f"Page {_doc.page}",
        )
        canvas.setStrokeColor(BORDER)
        canvas.line(doc.leftMargin, 16 * mm,
                    pagesize[0] - doc.rightMargin, 16 * mm)
        canvas.setStrokeColor(BORDER)
        canvas.line(doc.leftMargin, pagesize[1] - 13 * mm,
                    pagesize[0] - doc.rightMargin, pagesize[1] - 13 * mm)
        canvas.restoreState()

    doc.addPageTemplates([PageTemplate(id="default", frames=[frame], onPage=_on_page)])
    return doc


def _esc(text) -> str:
    """Escape the four chars reportlab's mini-XML treats as markup."""
    return (
        str(text or "")
        .replace("&", "&amp;")
        .replace("<", "&lt;")
        .replace(">", "&gt;")
    )


def _para(text, style):
    """Plain-text paragraph — escapes any markup characters."""
    if not text:
        return None
    return Paragraph(_esc(text), style)


def _rich(markup, style):
    """Paragraph that *renders* reportlab markup (<b>, <i>, <font>).
    Caller MUST `_esc()` any user-provided interpolations themselves.
    """
    if not markup:
        return None
    return Paragraph(markup, style)


def _safe_region(region_name: str) -> str:
    """Belt-and-braces guard against a legacy region.name = "Your location"
    leak. An older version of the geo-detect endpoints used to write that
    literal string when no city could be resolved; we now block it at
    every layer, but stale localStorage means it's worth a final check
    here to avoid an embarrassing PDF cover.
    """
    if not region_name or region_name.strip().lower() in {
        "your location", "unknown location", "",
    }:
        return "your garden"
    return region_name


# ──────────────────────── section builders ─────────────────────────────────

def _section_cover(story, *, region_name, month_label, month, styles):
    """Cover-page eyebrow + title + intro. Includes a small seasonal
    vignette above the eyebrow when a month is supplied so the printed
    page reads like a magazine plate rather than a generated form."""
    if month is not None:
        illo = monthly_drawing(month, target_width_mm=24.0)
        if illo is not None:
            story.append(illo)
            story.append(Spacer(1, 3 * mm))
    story += [
        _para("SEASONAL GROWING JOURNAL", styles["eyebrow"]),
        _para(f"{month_label} — {region_name}", styles["h1"]),
        _para(
            f"Personalised for {region_name}. Use this as a working print-out — "
            "tick tasks as you do them, jot the variety you sowed in the margin, "
            "circle anything you want to try next year.",
            styles["body"],
        ),
        Spacer(1, 4 * mm),
    ]


def _section_plant_now(story, plants, styles):
    if not plants:
        return
    story.append(_para("Sow & plant this month", styles["h2"]))
    for p in plants:
        block = [_rich(
            f"<b>{_esc((p.get('name') or '').strip())}</b>"
            + (f"  <font color='#5C6B57'>· {_esc(p.get('kind'))}</font>" if p.get("kind") else ""),
            styles["h3"],
        )]
        if p.get("why"):
            block.append(_para(p["why"], styles["body"]))
        if p.get("how"):
            block.append(_rich(f"<i>How:</i> {_esc(p['how'])}", styles["small"]))
        story.append(KeepTogether([b for b in block if b]))


def _section_harvest(story, items, styles):
    if not items:
        return
    story.append(_para("Harvest now", styles["h2"]))
    for h in items:
        block = [_rich(f"<b>{_esc((h.get('name') or '').strip())}</b>", styles["h3"])]
        if h.get("tip"):
            block.append(_para(h["tip"], styles["body"]))
        story.append(KeepTogether(block))


def _section_tasks(story, items, styles):
    if not items:
        return
    story.append(PageBreak())
    story.append(_para("Tasks", styles["h2"]))
    for t in items:
        block = [_rich(f"<b>☐ {_esc((t.get('title') or '').strip())}</b>", styles["h3"])]
        if t.get("detail"):
            block.append(_para(t["detail"], styles["body"]))
        story.append(KeepTogether(block))


def _section_pests(story, items, styles):
    if not items:
        return
    story.append(_para("Pest watch", styles["h2"]))
    for pest in items:
        block = [_rich(f"<b>{_esc((pest.get('name') or '').strip())}</b>", styles["h3"])]
        if pest.get("signs"):
            block.append(_rich(f"<i>Signs:</i> {_esc(pest['signs'])}", styles["body"]))
        if pest.get("control"):
            block.append(_rich(f"<i>Control:</i> {_esc(pest['control'])}", styles["body"]))
        story.append(KeepTogether(block))


def _section_my_notes_grid(story, *, content_w, region_name, month_label, styles):
    """Blank grid the user pens in by hand. Always rendered on its own page
    so people can detach + tuck inside the back cover of a seed binder.
    Column widths sized to the active page (portrait or landscape)."""
    story.append(PageBreak())
    story.append(_para(f"My notes — {month_label}, {region_name}", styles["h2"]))
    story.append(_para(
        "Jot down what you actually planted, where, and how it grew. "
        "Future you (and next year's PDF) will thank you.",
        styles["body"],
    ))
    story.append(Spacer(1, 3 * mm))

    col_widths = [
        content_w * 0.14,  # Date
        content_w * 0.26,  # Sown / planted
        content_w * 0.22,  # Where
        content_w * 0.38,  # Notes
    ]
    header = ["Date", "Sown / planted", "Where", "Notes / how it went"]
    rows = [header] + [[""] * 4 for _ in range(18)]

    notes_tbl = Table(rows, colWidths=col_widths, rowHeights=[8 * mm] + [11 * mm] * 18)
    notes_tbl.setStyle(TableStyle([
        ("FONT", (0, 0), (-1, 0), "Helvetica-Bold", 9),
        ("TEXTCOLOR", (0, 0), (-1, 0), FOREST),
        ("BACKGROUND", (0, 0), (-1, 0), SAND),
        ("LINEBELOW", (0, 0), (-1, 0), 0.6, FOREST),
        ("GRID", (0, 1), (-1, -1), 0.3, BORDER),
        ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
        ("LEFTPADDING", (0, 0), (-1, -1), 4),
        ("RIGHTPADDING", (0, 0), (-1, -1), 4),
        ("TOPPADDING", (0, 0), (-1, 0), 4),
        ("BOTTOMPADDING", (0, 0), (-1, 0), 4),
    ]))
    story.append(notes_tbl)


def _footer(story, *, qr_url, content_w, styles):
    """QR + small print, or just small print if no QR URL was provided."""
    if qr_url:
        qr_img = qrcode.make(qr_url)
        qr_buf = BytesIO()
        qr_img.save(qr_buf, format="PNG")
        qr_buf.seek(0)
        qr_flowable = RLImage(qr_buf, width=22 * mm, height=22 * mm)
        caption = _para(
            f"Scan to revisit this guide online — your access stays unlocked.   {qr_url}\n"
            "Generated by Patch & Pot. Climate, weather and microsites vary widely — "
            "treat this as a thoughtful starting point, not a strict rulebook.",
            styles["small"],
        )
        qr_row = Table(
            [[qr_flowable, caption]],
            colWidths=[26 * mm, content_w - 26 * mm],
        )
        qr_row.setStyle(TableStyle([
            ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
            ("LEFTPADDING", (0, 0), (-1, -1), 0),
            ("RIGHTPADDING", (0, 0), (-1, -1), 0),
            ("TOPPADDING", (0, 0), (-1, -1), 0),
            ("BOTTOMPADDING", (0, 0), (-1, -1), 0),
        ]))
        story.append(Spacer(1, 4 * mm))
        story.append(qr_row)
    else:
        story.append(Spacer(1, 6 * mm))
        story.append(_para(
            "Generated by Patch & Pot. Climate, weather and microsites vary widely — "
            "treat this as a thoughtful starting point, not a strict rulebook.",
            styles["small"],
        ))


# ──────────────────────── public entry point ───────────────────────────────

def build_seasonal_pdf(*, guidance: dict, region_name: str, month_label: str,
                       language: str, orientation: str = "portrait",
                       qr_url: str | None = None, month: int | None = None) -> bytes:
    """Render a full seasonal journal PDF.

    `guidance` is the JSON dict returned by /api/guidance — keys: plant_now,
    harvest_now, tasks, pests (each a list of typed objects).
    `qr_url` (optional): URL encoded into a small QR on the My-notes page so
    the printed PDF stays a re-entry point to the live site.
    `month` (optional, 1-12): if provided, a small seasonal vignette is
    rendered in the cover-page header (rose hip in October, sweet pea in
    June, etc.). Skipped silently if absent.
    """
    pagesize = landscape(A4) if orientation == "landscape" else A4
    buf = BytesIO()
    doc = _doc(buf, pagesize=pagesize)
    styles = _styles()
    region_name = _safe_region(region_name)
    content_w = pagesize[0] - 18 * mm * 2

    story: list = []
    _section_cover(story, region_name=region_name, month_label=month_label,
                   month=month, styles=styles)
    _section_plant_now(story, guidance.get("plant_now") or [], styles)
    _section_harvest(story, guidance.get("harvest_now") or [], styles)
    _section_tasks(story, guidance.get("tasks") or [], styles)
    _section_pests(story, guidance.get("pests") or [], styles)
    _section_my_notes_grid(story, content_w=content_w, region_name=region_name,
                           month_label=month_label, styles=styles)
    _footer(story, qr_url=qr_url, content_w=content_w, styles=styles)

    doc.build([item for item in story if item is not None])
    return buf.getvalue()
