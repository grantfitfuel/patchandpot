"""Split the monolithic /app/frontend/src/i18n/index.jsx into per-locale files
under /app/frontend/src/i18n/locales/{code}.js.

Each output file exports a default object: the locale's translation map. The
rewritten index.jsx statically imports `en` (the fallback) and dynamically
imports the active locale at runtime, so a French user only downloads the
French strings instead of all 58 languages.

After this script runs, the monolithic STRINGS block is gone — only the
React provider + the LANGS metadata array remain in index.jsx.

Run:
    cd /app && python scripts/split_i18n_locales.py
"""
import json
import re
import sys
from pathlib import Path

I18N_PATH    = Path("/app/frontend/src/i18n/index.jsx")
LOCALES_DIR  = Path("/app/frontend/src/i18n/locales")
LOCALES_DIR.mkdir(parents=True, exist_ok=True)


def find_block(text: str, lang_code: str) -> tuple[int, int] | None:
    """Return (start, end) byte offsets of `  {lang_code}: { … },` in `text`."""
    open_pat = re.compile(rf"^  {re.escape(lang_code)}:\s*\{{", flags=re.MULTILINE)
    om = open_pat.search(text)
    if not om:
        return None
    depth, i = 0, om.end() - 1
    while i < len(text):
        c = text[i]
        if c == "{":
            depth += 1
        elif c == "}":
            depth -= 1
            if depth == 0:
                # Consume trailing comma + newline if present so the parent
                # STRINGS dict remains syntactically valid as we delete blocks.
                j = i + 1
                while j < len(text) and text[j] in ",\n\r ":
                    j += 1
                return om.start(), j
        i += 1
    return None


def parse_kv_pairs(block: str) -> dict:
    """Parse a small subset of JS object syntax — just `"key": "value",` lines
    with optional trailing comma. The translation maps are deliberately flat
    so we don't need a full JS parser.

    Returns {key: value}. Values are decoded via json.loads after stripping
    the surrounding curlies.
    """
    # Strip the leading `  en: {` and trailing `}` / comma.
    body = re.sub(r"^[^\{]*\{", "", block, count=1, flags=re.DOTALL)
    body = body.rstrip().rstrip(",")
    body = re.sub(r"}\s*$", "", body)
    out: dict[str, str] = {}
    # Each pair: "key": "value with possible \" escapes",  (trailing comma optional)
    pair_re = re.compile(
        r'"((?:[^"\\]|\\.)+)"\s*:\s*"((?:[^"\\]|\\.)*)"\s*,?',
        flags=re.DOTALL,
    )
    for m in pair_re.finditer(body):
        key = json.loads(f'"{m.group(1)}"')
        val = json.loads(f'"{m.group(2)}"')
        out[key] = val
    return out


def js_object_literal(d: dict) -> str:
    """Render the dict as a JS object literal with deterministic key ordering
    and JSON-style string escaping. We rely on json.dumps for the value
    because that handles every Unicode + control-char case correctly."""
    lines = []
    for k in d:
        v = json.dumps(d[k], ensure_ascii=False)
        kk = json.dumps(k, ensure_ascii=False)
        lines.append(f"  {kk}: {v},")
    return "{\n" + "\n".join(lines) + "\n}"


def main():
    text = I18N_PATH.read_text()

    # Locate the STRINGS opening so we know where the per-locale blocks live.
    strings_pat = re.compile(r"^const STRINGS = \{", flags=re.MULTILINE)
    strings_m = strings_pat.search(text)
    if not strings_m:
        print("ERROR: couldn't find `const STRINGS = {` — has the file been rewritten already?", file=sys.stderr)
        sys.exit(1)

    # The LANGS metadata array stays in index.jsx — read its codes from there.
    langs_pat = re.compile(r"export const LANGUAGES = \[([\s\S]*?)\];", flags=re.MULTILINE)
    langs_m = langs_pat.search(text)
    if not langs_m:
        print("ERROR: couldn't find `export const LANGUAGES = [`", file=sys.stderr)
        sys.exit(1)
    codes = re.findall(r'code:\s*"([^"]+)"', langs_m.group(1))
    print(f"discovered {len(codes)} locales: {codes[:6]}…")

    # For each locale, find its block, parse it, write the per-locale file.
    written = []
    for code in codes:
        loc = find_block(text, code)
        if not loc:
            print(f"  ⚠ {code}: block not found, skipping")
            continue
        start, end = loc
        block = text[start:end]
        kvs = parse_kv_pairs(block)
        if not kvs:
            print(f"  ⚠ {code}: parsed 0 keys — skipping write")
            continue
        out_path = LOCALES_DIR / f"{code}.js"
        out_path.write_text(
            "// AUTO-GENERATED by scripts/split_i18n_locales.py — do not edit by hand.\n"
            "// To update a single string, edit this file directly; to add a brand-new\n"
            "// key, add it to the English file (en.js) and run a translation script.\n\n"
            "const dict = " + js_object_literal(kvs) + ";\n\n"
            "export default dict;\n"
        )
        written.append((code, len(kvs)))

    print()
    print("wrote", len(written), "locale files")
    for c, n in written[:5]:
        print(f"  {c}: {n} keys → /app/frontend/src/i18n/locales/{c}.js")
    print("  …")
    en_count = next((n for c, n in written if c == "en"), None)
    print(f"  en: {en_count} keys (fallback)")


if __name__ == "__main__":
    main()
