def apply_meta(plants: list[dict]) -> None:
    """Mutate the catalogue in place — add lifecycle, hardiness, botanical."""
    for p in plants:
        lc, hd = _META.get(p["id"], ("annual", "hardy"))
        p["lifecycle"] = lc
        p["hardiness"] = hd
        p["botanical"] = _BOTANICAL.get(p["id"], "")
