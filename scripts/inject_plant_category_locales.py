def inject(path: pathlib.Path, code: str) -> str:
    text = path.read_text(encoding="utf-8")
    if "plants.category.cut-flower" in text:
        return "skip-exists"
    if code not in T:
        return "skip-no-translation"
    block_lines = []
    for key in [
        "plants.category.cut-flower",
        "plants.category.brassica",
        "plants.category.legume",
        "plants.category.squash",
        "plants.category.sprouts",
        "plants.category.shrub",
        "plants.category.climber",
        "plants.group.all",
        "plants.group.edibles",
        "plants.group.herbs",
        "plants.group.fruit",
        "plants.group.flowers",
        "plants.group.cut-flowers",
        "plants.group.shrubs",
        "plants.group.sprouts",
    ]:
        val = T[code][key].replace('"', '\\"')
        block_lines.append(f'  "{key}": "{val}",')
    block = "\n".join(block_lines)

    # Find the line with "plants.category.flower" and insert after it.
    pattern = re.compile(r'(^[ \t]*"plants\.category\.flower":[^\n]*\n)', re.MULTILINE)
    new_text, n = pattern.subn(rf"\1{block}\n", text, count=1)
    if n != 1:
        return "no-anchor"
    path.write_text(new_text, encoding="utf-8")
    return "ok"


def main() -> int:
    files = sorted(LOCALES_DIR.glob("*.js"))
    counts = {"ok": 0, "skip-exists": 0, "skip-no-translation": 0, "no-anchor": 0}
    for f in files:
        if f.stem == "en":
            continue
        result = inject(f, f.stem)
        counts[result] = counts.get(result, 0) + 1
        print(f"  {f.stem:5s} {result}")
    print()
    print("Summary:", counts)
    return 0 if counts["no-anchor"] == 0 else 1


